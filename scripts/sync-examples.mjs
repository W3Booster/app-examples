import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { generateSettingsBinding } from '@w3booster/sdk/settings';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Use --check for offline verification, or no argument to sync public definitions.');
const catalog = JSON.parse(await readFile(resolve(root, 'examples.json'), 'utf8'));
const stable = value => Array.isArray(value) ? `[${value.map(stable).join(',')}]`
  : value && typeof value === 'object' ? `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${stable(value[key])}`).join(',')}}` : JSON.stringify(value);
const files = new Map();
const manifest = { examples: [] };
const imports = ["// Generated by npm run examples:sync. New starter projects replace this module.", "import { w3boosterApp as starter } from './w3booster.generated';"];
const cases = [];
for (const [index, item] of catalog.entries()) {
  if (!/^[a-z]+(?:-[a-z]+)*$/.test(item.slug)) throw new Error('Invalid example slug.');
  const contract = { clientId: item.clientId, scopes: item.scopes, settingsSchema: item.settingsSchema };
  const revision = createHash('sha256').update(stable(contract)).digest('hex');
  const definition = { ...contract, revision };
  if (!check) {
    const response = await fetch(`https://api.w3booster.com/stream/v1/app-definitions/${item.clientId}`, { signal: AbortSignal.timeout(10000) });
    if (!response.ok || stable(await response.json()) !== stable(definition)) throw new Error(`${item.slug}: stage the matching database definition before generating its binding.`);
  }
  files.set(`src/registered/${item.slug}.ts`, generateSettingsBinding(definition));
  imports.push(`import { w3boosterApp as app${index} } from './registered/${item.slug}';`);
  cases.push(`    case '${item.slug}': return app${index};`);
  manifest.examples.push({ slug: item.slug, clientId: item.clientId, revision });
}
files.set('src/application.ts', `${imports.join('\n')}\nexport function getApplication(slug: string | null) {\n  switch (slug) {\n    case null: return starter;\n${cases.join('\n')}\n    default: throw new Error('Unknown example application. Open it from the W3Booster example catalog.');\n  }\n}\n`);
files.set('public/example-bindings.json', `${JSON.stringify(manifest, null, 2)}\n`);
for (const [file, content] of files) {
  const path = resolve(root, file);
  if (check) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`${file} is stale; run npm run examples:sync.`);
  } else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, content); }
}
console.log(`${check ? 'Verified' : 'Synchronized'} ${catalog.length} registered example bindings and the deployment manifest.`);
